'use client'

import { useState, useCallback } from 'react'
import { analyzeResume, type AnalysisResult } from '@/lib/scorer'

const CATEGORY_COLORS: Record<string, string> = {
  Language: 'badge-language',
  Frontend: 'badge-frontend',
  Backend: 'badge-backend',
  Database: 'badge-database',
  Cloud: 'badge-cloud',
  DevOps: 'badge-devops',
  'AI/ML': 'badge-ai-ml',
  Tools: 'badge-tools',
  Design: 'badge-design',
  Methodology: 'badge-methodology',
}

function scoreColor(score: number): string {
  if (score >= 80) return '#3fb950'
  if (score >= 60) return '#d29922'
  return '#f85149'
}

function scoreLabel(score: number): string {
  if (score >= 85) return 'Excellent'
  if (score >= 70) return 'Good'
  if (score >= 55) return 'Fair'
  if (score >= 40) return 'Needs Work'
  return 'Poor'
}

function fillClass(pct: number): string {
  if (pct >= 75) return 'good'
  if (pct >= 45) return 'ok'
  return 'bad'
}

interface ScoreRingProps {
  score: number
}

function ScoreRing({ score }: ScoreRingProps) {
  const size = 160
  const r = 64
  const cx = size / 2
  const cy = size / 2
  const circ = 2 * Math.PI * r
  const offset = circ * (1 - score / 100)
  const color = scoreColor(score)

  return (
    <div className="score-ring-wrap" style={{ width: size, height: size }}>
      <svg width={size} height={size}>
        <circle
          cx={cx} cy={cy} r={r}
          fill="none"
          stroke="#1c2230"
          strokeWidth={12}
        />
        <circle
          cx={cx} cy={cy} r={r}
          fill="none"
          stroke={color}
          strokeWidth={12}
          strokeLinecap="round"
          strokeDasharray={circ}
          strokeDashoffset={offset}
          style={{ transition: 'stroke-dashoffset 0.8s cubic-bezier(0.22,1,0.36,1)' }}
        />
      </svg>
      <div className="score-ring-label">
        <div style={{ fontSize: 36, fontWeight: 800, color, lineHeight: 1 }}>{score}</div>
        <div style={{ fontSize: 13, color: '#8b949e', marginTop: 4 }}>{scoreLabel(score)}</div>
      </div>
    </div>
  )
}

interface DimensionBarProps {
  label: string
  score: number
  max: number
  icon: string
}

function DimensionBar({ label, score, max, icon }: DimensionBarProps) {
  const pct = Math.round((score / max) * 100)
  const cls = fillClass(pct)
  return (
    <div style={{ marginBottom: 14 }}>
      <div style={{ display: 'flex', justifyContent: 'space-between', marginBottom: 6, alignItems: 'center' }}>
        <span style={{ fontSize: 14, color: '#e6edf3', display: 'flex', alignItems: 'center', gap: 6 }}>
          <span>{icon}</span> {label}
        </span>
        <span style={{ fontSize: 13, color: '#8b949e', fontVariantNumeric: 'tabular-nums' }}>
          {score}/{max}
        </span>
      </div>
      <div className="progress-track">
        <div
          className={`progress-fill ${cls}`}
          style={{ width: `${pct}%` }}
        />
      </div>
    </div>
  )
}

function generateTextReport(result: AnalysisResult, resumeText: string): string {
  const lines: string[] = [
    '═══════════════════════════════════',
    '   RESUME SCORER — ANALYSIS REPORT ',
    '═══════════════════════════════════',
    '',
    `TOTAL SCORE: ${result.totalScore}/100 (${scoreLabel(result.totalScore)})`,
    '',
    'BREAKDOWN:',
    `  Contact Info:     ${result.breakdown.contactInfo}/20`,
    `  Work Experience:  ${result.breakdown.workExperience}/25`,
    `  Skills:           ${result.breakdown.skills}/25`,
    `  Education:        ${result.breakdown.education}/15`,
    `  Formatting:       ${result.breakdown.formatting}/15`,
    '',
    `Word Count: ${result.wordCount}`,
    '',
    'IMPROVEMENT SUGGESTIONS:',
  ]
  result.suggestions.forEach((s, i) => {
    lines.push(`  ${i + 1}. [${s.category}] ${s.text}`)
  })
  if (result.keywords.length > 0) {
    lines.push('')
    lines.push('DETECTED KEYWORDS:')
    lines.push('  ' + result.keywords.map(k => k.word).join(', '))
  }
  lines.push('')
  lines.push('Generated by Resume Scorer')
  return lines.join('\n')
}

export default function HomePage() {
  const [resumeText, setResumeText] = useState('')
  const [jobTitle, setJobTitle] = useState('')
  const [loading, setLoading] = useState(false)
  const [result, setResult] = useState<AnalysisResult | null>(null)
  const [copied, setCopied] = useState(false)

  const handleAnalyze = useCallback(() => {
    if (!resumeText.trim()) return
    setLoading(true)
    setResult(null)
    setTimeout(() => {
      const res = analyzeResume(resumeText, jobTitle || undefined)
      setResult(res)
      setLoading(false)
    }, 1500)
  }, [resumeText, jobTitle])

  const handleReset = () => {
    setResult(null)
    setResumeText('')
    setJobTitle('')
  }

  const handleCopy = async () => {
    if (!result) return
    const report = generateTextReport(result, resumeText)
    try {
      await navigator.clipboard.writeText(report)
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    } catch {
      // fallback: select textarea
    }
  }

  return (
    <main style={{ minHeight: '100vh', paddingBottom: 60 }}>
      {/* Header */}
      <header style={{
        borderBottom: '1px solid #30363d',
        background: '#161b22',
        padding: '16px 0',
        marginBottom: 40,
      }}>
        <div className="container" style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between' }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: 10 }}>
            <span style={{ fontSize: 22 }}>📄</span>
            <span style={{ fontWeight: 800, fontSize: 18, color: '#e6edf3' }}>Resume Scorer</span>
          </div>
          <span style={{
            fontSize: 12,
            color: '#3fb950',
            background: 'rgba(63,185,80,0.12)',
            border: '1px solid rgba(63,185,80,0.3)',
            borderRadius: 100,
            padding: '3px 10px',
            fontWeight: 600,
          }}>
            Free · No Signup
          </span>
        </div>
      </header>

      <div className="container">
        {/* Hero */}
        {!result && (
          <div style={{ textAlign: 'center', marginBottom: 36 }}>
            <h1 style={{ fontSize: 36, fontWeight: 800, lineHeight: 1.2, marginBottom: 12 }}>
              Get Your Resume Scored{' '}
              <span style={{ color: '#58a6ff' }}>Instantly</span>
            </h1>
            <p style={{ color: '#8b949e', fontSize: 16, maxWidth: 500, margin: '0 auto' }}>
              Paste your resume text below. Our engine checks contact info, experience,
              skills, education, and formatting — in seconds.
            </p>
          </div>
        )}

        {/* Input section */}
        {!result && (
          <div className="card fade-up" style={{ marginBottom: 24 }}>
            <div style={{ marginBottom: 18 }}>
              <label className="label" htmlFor="resume-input">
                Resume Text
              </label>
              <textarea
                id="resume-input"
                className="textarea"
                placeholder="Paste your full resume here…&#10;&#10;Include your contact info, work experience, skills, and education for the most accurate score."
                value={resumeText}
                onChange={e => setResumeText(e.target.value)}
                style={{ minHeight: 280 }}
              />
              <div style={{ display: 'flex', justifyContent: 'flex-end', marginTop: 6 }}>
                <span style={{ fontSize: 12, color: '#4d5566' }}>
                  {resumeText.trim().split(/\s+/).filter(w => w).length} words
                </span>
              </div>
            </div>

            <div style={{ marginBottom: 24 }}>
              <label className="label" htmlFor="job-title">
                Target Job Title <span style={{ color: '#4d5566', textTransform: 'none', fontWeight: 400 }}>(optional)</span>
              </label>
              <input
                id="job-title"
                className="input"
                type="text"
                placeholder="e.g. Senior Frontend Engineer, Product Manager…"
                value={jobTitle}
                onChange={e => setJobTitle(e.target.value)}
              />
            </div>

            <div style={{ display: 'flex', justifyContent: 'center' }}>
              <button
                className="btn btn-primary btn-lg"
                onClick={handleAnalyze}
                disabled={loading || resumeText.trim().length < 30}
              >
                {loading ? (
                  <>
                    <span className="spinner" />
                    Analyzing…
                  </>
                ) : (
                  <>
                    ⚡ Analyze My Resume
                  </>
                )}
              </button>
            </div>

            {resumeText.trim().length > 0 && resumeText.trim().length < 30 && (
              <p style={{ textAlign: 'center', marginTop: 10, color: '#f85149', fontSize: 13 }}>
                Please paste more of your resume (at least a few sentences).
              </p>
            )}
          </div>
        )}

        {/* Loading state */}
        {loading && (
          <div className="card fade-up" style={{ textAlign: 'center', padding: '48px 24px' }}>
            <div className="spinner" style={{ width: 36, height: 36, borderWidth: 3, margin: '0 auto 16px' }} />
            <p style={{ color: '#8b949e' }}>Scanning your resume…</p>
          </div>
        )}

        {/* Results */}
        {result && !loading && (
          <div className="fade-up">
            {/* Top bar */}
            <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: 24 }}>
              <h2 style={{ fontWeight: 700, fontSize: 20 }}>Your Results</h2>
              <div style={{ display: 'flex', gap: 10 }}>
                <button className="btn btn-ghost" onClick={handleCopy}>
                  {copied ? '✓ Copied!' : '📋 Copy Report'}
                </button>
                <button className="btn btn-secondary" onClick={handleReset}>
                  ↩ Re-analyze
                </button>
              </div>
            </div>

            {/* Score + breakdown */}
            <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 20, marginBottom: 20 }}>
              {/* Score ring card */}
              <div className="card" style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', justifyContent: 'center', gap: 16, padding: '32px 24px' }}>
                <ScoreRing score={result.totalScore} />
                <div style={{ textAlign: 'center' }}>
                  <div style={{ fontSize: 13, color: '#8b949e' }}>
                    {result.wordCount} words detected
                  </div>
                  {jobTitle && (
                    <div style={{ fontSize: 13, color: '#58a6ff', marginTop: 4 }}>
                      Target: {jobTitle}
                    </div>
                  )}
                  {result.targetMatch && (
                    <div className="target-match">
                      Title terms found in resume: {result.targetMatch.matchedTerms.length}/
                      {result.targetMatch.matchedTerms.length + result.targetMatch.missingTerms.length}
                      {result.targetMatch.missingTerms.length > 0 && ` · missing: ${result.targetMatch.missingTerms.join(', ')}`}
                    </div>
                  )}
                </div>
              </div>

              {/* Breakdown card */}
              <div className="card">
                <div className="section-title">Score Breakdown</div>
                <DimensionBar label="Contact Info" score={result.breakdown.contactInfo} max={20} icon="👤" />
                <DimensionBar label="Work Experience" score={result.breakdown.workExperience} max={25} icon="💼" />
                <DimensionBar label="Skills" score={result.breakdown.skills} max={25} icon="⚙️" />
                <DimensionBar label="Education" score={result.breakdown.education} max={15} icon="🎓" />
                <DimensionBar label="Formatting" score={result.breakdown.formatting} max={15} icon="📐" />
              </div>
            </div>

            {/* Suggestions */}
            {result.suggestions.length > 0 && (
              <div className="card" style={{ marginBottom: 20 }}>
                <div className="section-title">💡 Improvement Suggestions</div>
                <div>
                  {result.suggestions.map((s, i) => (
                    <div key={i} className="suggestion-item">
                      <div className="suggestion-dot" />
                      <div>
                        <span style={{
                          fontSize: 11,
                          fontWeight: 700,
                          color: '#58a6ff',
                          textTransform: 'uppercase',
                          letterSpacing: '0.05em',
                          display: 'block',
                          marginBottom: 2,
                        }}>
                          {s.category}
                        </span>
                        <span style={{ fontSize: 14, color: '#c9d1d9' }}>{s.text}</span>
                      </div>
                    </div>
                  ))}
                </div>
              </div>
            )}

            {/* Keywords */}
            {result.keywords.length > 0 && (
              <div className="card" style={{ marginBottom: 20 }}>
                <div className="section-title">🔍 Detected Keywords</div>
                <p style={{ fontSize: 13, color: '#8b949e', marginBottom: 14 }}>
                  {result.keywords.length} technical keyword{result.keywords.length !== 1 ? 's' : ''} found in your resume
                </p>
                <div style={{ display: 'flex', flexWrap: 'wrap', gap: 8 }}>
                  {result.keywords.map((kw, i) => (
                    <span
                      key={i}
                      className={`badge ${CATEGORY_COLORS[kw.category] ?? 'badge-default'}`}
                    >
                      {kw.word}
                    </span>
                  ))}
                </div>
              </div>
            )}

            {/* No keywords fallback */}
            {result.keywords.length === 0 && (
              <div className="card" style={{ marginBottom: 20 }}>
                <div className="section-title">🔍 Keywords</div>
                <p style={{ color: '#8b949e', fontSize: 14 }}>
                  No common technical keywords detected. Add a Skills section listing
                  your tools, languages, and frameworks.
                </p>
              </div>
            )}

            {/* Pro upsell */}
            <div style={{
              background: 'linear-gradient(135deg, #1f3a5f 0%, #1a2a3a 100%)',
              border: '1px solid #1f6feb',
              borderRadius: 12,
              padding: '20px 24px',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              gap: 16,
            }}>
              <div>
                <div style={{ fontWeight: 700, fontSize: 15, marginBottom: 4 }}>
                  ✨ Go Pro — Unlimited Analyses
                </div>
                <div style={{ color: '#8b949e', fontSize: 13 }}>
                  ATS keyword matching · LinkedIn profile tips · Cover letter hints
                </div>
              </div>
              <button className="btn btn-primary" style={{ flexShrink: 0 }}>
                Upgrade $12/mo
              </button>
            </div>
          </div>
        )}
      </div>
    </main>
  )
}
